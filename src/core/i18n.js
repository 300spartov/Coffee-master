let currentLang = localStorage.getItem('cm_lang') || 'ua';

function t(key) {
  return (LANG[currentLang] && LANG[currentLang][key]) || (LANG['ua'] && LANG['ua'][key]) || key;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('cm_lang', lang);
  applyLangToDOM();
  /* Перерендерити динамічні секції */
  if (typeof renderFeed === 'function') renderFeed();
  if (typeof renderProf === 'function') renderProf();
}

/* Оновити всі data-i18n елементи без повного ре-рендеру */
function applyLangToDOM() {
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-ph');
    el.placeholder = t(key);
  });
  /* Оновити кнопки перемикача мови */
  var btnUA = document.getElementById('lang-ua-btn');
  var btnEN = document.getElementById('lang-en-btn');
  if (btnUA) btnUA.classList.toggle('on', currentLang === 'ua');
  if (btnEN) btnEN.classList.toggle('on', currentLang === 'en');
  /* Оновити brew-title / brew-sub */
  var brewTitle = document.getElementById('brew-title');
  if (brewTitle) brewTitle.textContent = t('brew_title');
  var brewSub = document.getElementById('brew-sub');
  if (brewSub) brewSub.textContent = t('brew_subtitle');
}

/* Зворотний переклад збережених смаків (старі рецепти — UA рядки) */
function translateFlavor(str) {
  if (!str) return str;
  if (typeof str === 'object') str = str.ua || str.en || String(str);
  if (currentLang === 'ua') return str; /* UA → UA, нічого робити */
  /* Шукаємо в FLAVORS: UA note → EN note */
  if (window.FLAT_NOTES) {
    var found = window.FLAT_NOTES.find(function(f){ return f.note === str; });
    if (found && found.desc && typeof found.desc === 'object') {
      return found.desc.en || str;
    }
  }
  /* Fallback: шукаємо категорію/підкатегорію */
  if (window.FLAVORS) {
    for (var ci=0; ci<window.FLAVORS.length; ci++) {
      var cat = window.FLAVORS[ci];
      if ((cat.label_ua||cat.label) === str) return cat.label_en || str;
      var subs = cat.subs || [];
      for (var si=0; si<subs.length; si++) {
        if ((subs[si].label_ua||subs[si].label) === str) return subs[si].label_en || str;
      }
    }
  }
  return str;
}
